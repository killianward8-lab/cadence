#!/usr/bin/env python3
"""Join the four editable files into cadence.json (the shape the live page stores).

Run from the repo root:  python3 tools/assemble.py
Also rewrites SCRIPT.md and OBJECTIONS.md so the readable copies stay in sync.
"""
import json, pathlib, time
root = pathlib.Path(__file__).resolve().parent.parent
load = lambda n: json.loads((root / n).read_text(encoding="utf-8"))
doc = {"stages": load("stages.json")}
v = load("versions.json")
doc["obv"] = v["obv"]
doc["objections"] = load("objections.json")
doc["ov"] = v["ov"]
doc["offers"] = load("offers.json")
doc["coaches"] = load("coaches.json")
doc["offv"] = v["offv"]
doc["updated"] = int(time.time() * 1000)
(root / "cadence.json").write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

# readable copies
out = ["# Killian's call script\n", "Edit `stages.json`, not this file. This is generated by `tools/assemble.py`.\n"]
for s in doc["stages"]:
    out.append(f"\n## Stage {s['n']} · {s['name']}" + ("  (gate: don't pitch yet)" if s.get("gate") else "") + "\n")
    for var in s["variants"]:
        out.append(f"\n### {var['label']}  `{var['id']}`\n")
        for i, line in enumerate(var["flow"], 1):
            out.append(f"{i}. {line}\n")
(root / "SCRIPT.md").write_text("".join(out), encoding="utf-8")

out = ["# Objections\n", "Edit `objections.json`, not this file. Generated by `tools/assemble.py`.\n"]
group = None
for o in doc["objections"]:
    g = f"{o['cat']} · {o['group']}"
    if g != group:
        group = g
        out.append(f"\n## {g}\n")
    out.append(f"\n### \"{o['q']}\"  `{o['id']}`\n")
    for tag, line in o["lines"]:
        out.append(f"- **{tag}:** {line}\n")
    for k, label in [("rname", "Reframe"), ("aname", "Analogy")]:
        if o.get(k):
            body = o["reframe" if k == "rname" else "analogy"].replace("\n", "  \n  ")
            ask = o.get("rask" if k == "rname" else "aask", "")
            out.append(f"- **{label} · {o[k]}** ({ask})  \n  {body}\n")
    if o.get("next"):
        out.append("- **Next:** " + o["next"].replace("\n", "  \n  ") + "\n")
    out.append("- **Close:** " + o["close"].replace("\n", "  \n  ") + "\n")
(root / "OBJECTIONS.md").write_text("".join(out), encoding="utf-8")
print("wrote cadence.json, SCRIPT.md, OBJECTIONS.md")
